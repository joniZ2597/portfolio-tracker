  assert.notDeepStrictEqual(c.buildMap(crlf, SYN_REGIONS).fileSha256, c.buildMap(SYN, SYN_REGIONS).fileSha256, 'negative control: the raw CRLF text hashes differently');
  const seed = JSON.stringify({ schema: 'index-pins/v1', regions: SYN_REGIONS }, null, 2) + '\n';
