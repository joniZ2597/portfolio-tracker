// ── IP-2: a 1-byte change inside a function changes exactly that function's entry ─────────────────────────
test('IP-2: a one-byte change inside a function changes exactly that function entry (and nothing else)', () => {
  const c = core();
  const base = c.buildMap(SYN, SYN_REGIONS);
  assert.deepStrictEqual(Object.keys(base.functions).sort(), ['alpha', 'beta']);
  const m = c.buildMap(mutate(SYN, '  return await alpha(1);', '  return await alpha(2);'), SYN_REGIONS);
  assert.deepStrictEqual(changedNames(base, m), ['functions.beta']);
  assert.strictEqual(m.remainderSha256, base.remainderSha256);
  assert.deepStrictEqual(m.regions, base.regions);
  // negative control: an unchanged text is not reported
  assert.deepStrictEqual(changedNames(base, c.buildMap(SYN, SYN_REGIONS)), []);
  // the suite-side helper (used by the 13 migrated suites): reports exactly the requested entries that differ
  const mutatedText = mutate(SYN, '  return await alpha(1);', '  return await alpha(2);');
  assert.deepStrictEqual(c.entryMismatches(mutatedText, base, ['functions.alpha', 'functions.beta', 'regions.pf', 'remainder']), ['functions.beta']);
  assert.deepStrictEqual(c.entryMismatches(SYN, base, ['functions.alpha', 'functions.beta', 'regions.pf', 'remainder']), []);
  assert.deepStrictEqual(c.entryMismatches(SYN, base, ['functions.nope']), ['functions.nope'], 'an entry missing from the map is reported, never passed');
  assert.deepStrictEqual(c.entryMismatches(SYN, { regions: { pf: { start: '// NOPE', end: '// NOPE2' } } }, ['functions.alpha']), ['functions.alpha'], 'an uncomputable map fails closed');
  assert.deepStrictEqual(c.entryNamesExcept(base, ['functions.alpha', 'remainder']).sort(), ['functions.beta', 'regions.css', 'regions.inner', 'regions.pf']);
});

// ── IP-3: a 1-byte change inside a named region changes exactly that region (and its enclosing function) ───
test('IP-3: a one-byte change inside a region changes that region; inside a function, also the enclosing function', () => {
  const c = core();
  const base = c.buildMap(SYN, SYN_REGIONS);
  const outside = c.buildMap(mutate(SYN, 'var PF_X = 5;', 'var PF_X = 6;'), SYN_REGIONS);
  assert.deepStrictEqual(changedNames(base, outside), ['regions.pf']);
  assert.strictEqual(outside.remainderSha256, base.remainderSha256, 'an out-of-function region is masked out of the remainder');
  const css = c.buildMap(mutate(SYN, '.a { color: red; }', '.a { color: blue; }'), SYN_REGIONS);
  assert.deepStrictEqual(changedNames(base, css), ['regions.css']);
  const inner = c.buildMap(mutate(SYN, '  var k = 2;', '  var k = 3;'), SYN_REGIONS);
  assert.deepStrictEqual(changedNames(base, inner), ['functions.alpha', 'regions.inner']);
  assert.strictEqual(inner.remainderSha256, base.remainderSha256);
  // each region digest is the digest of exactly its span (start anchor through end anchor, inclusive)
  const span = SYN.slice(SYN.indexOf('// PF-BEGIN'), SYN.indexOf('// PF-END') + '// PF-END'.length);
  assert.strictEqual(base.regions.pf.sha256, sha256(span));
});

