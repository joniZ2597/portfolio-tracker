// ── plumbing ────────────────────────────────────────────────────────────────────────────────────
function lf(s) { return String(s).replace(/\r\n/g, '\n'); }
function sha256(s) { return crypto.createHash('sha256').update(s).digest('hex'); }
function countOf(hay, needle) { return needle ? hay.split(needle).length - 1 : 0; }
// Mutate exactly one occurrence of an anchor; a zero or double match is a harness defect, not a pass.
function mutate(text, anchor, replacement) {
  const n = countOf(text, anchor);
  if (n !== 1) throw new Error('harness defect: anchor occurs ' + n + ' time(s), expected exactly 1: ' + JSON.stringify(anchor));
  return text.replace(anchor, () => replacement);
}
let coreErr = null;
let coreMod = null;
try { coreMod = require(CORE_PATH); } catch (e) { coreErr = e; }
function core() {
  if (!coreMod) throw new Error('RED: qa/lib/index-pins-core.js is not loadable (' + (coreErr && coreErr.code ? coreErr.code : 'error') + ')');
  return coreMod;
}
function needTool() {
  if (!fs.existsSync(TOOL_PATH)) throw new Error('RED: qa/tools/index-pins.js does not exist');
}
function tool(args) {
  needTool();
  const r = spawnSync(process.execPath, [TOOL_PATH].concat(args), { encoding: 'utf8', windowsHide: true, maxBuffer: 64 * 1024 * 1024 });
  assert.ok(!/MODULE_NOT_FOUND/.test(String(r.stderr)), 'tool failed to load: ' + String(r.stderr).split('\n')[0]);
  return r;
}
function mkTmp(prefix) { return fs.mkdtempSync(path.join(os.tmpdir(), prefix)); }
function rmrf(p) { fs.rmSync(p, { recursive: true, force: true }); }
function W(file, content) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, content); }
function snapshotDir(dir) {
  const out = {};
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      if (e.name === '.git') continue;
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p); else out[path.relative(dir, p).replace(/\\/g, '/')] = sha256(fs.readFileSync(p));
    }
  })(dir);
  return out;
}
function G(args, cwd) {
  const r = spawnSync('git', ['-c', 'user.name=ptqa', '-c', 'user.email=ptqa@example.invalid', '-c', 'commit.gpgsign=false', '-c', 'core.autocrlf=false'].concat(args), { cwd, encoding: 'utf8', windowsHide: true });
  if (r.status !== 0) throw new Error('git ' + args.join(' ') + ' failed: ' + (r.stderr || r.stdout));
  return String(r.stdout);
}

