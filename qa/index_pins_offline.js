    assert.notDeepStrictEqual(entryLines(r.stdout + 'changed  functions.alpha\n'), expectedEntries);
    assert.notDeepStrictEqual(entryLines(r.stdout.replace('changed  regions.pf', '')), expectedEntries);
    assert.ok(/^-\s+return await alpha\(1\);/m.test(r.stdout) && /^\+\s+return await alpha\(2\);/m.test(r.stdout), 'unified line diff of the changed function: ' + r.stdout);
