function parityMismatches(spans, content, names, opts) {
  const byName = {};
  for (const s of spans) if (!(s.name in byName)) byName[s.name] = s;
  const bad = [];
  for (const n of names) {
    const ref = refExtract(content, n, opts);
    const got = byName[n] ? byName[n].text : null;
    if (ref === null || got === null || ref !== got) bad.push(n);
  }
  return bad;
}
