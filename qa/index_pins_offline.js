// ── IP-11: the extractor agrees byte-for-byte with the existing extractors for every function a suite named ──
// REF_EXTRACT is a COPY of the extractor the 13 pinning suites carry today (indexOf('function NAME(') + async prefix +
// character brace matching; when the braces never close, the column-0 closing-brace rule of high1y_label / pulse_analyst_view).
// NAMED is the set of top-level functions named (quoted or as a key) anywhere in those 13 suites at baseline f40d6b6.
function refExtract(content, name, opts) {
  const o = opts || {};
  const sig = 'function ' + name + '(';
  const start = content.indexOf(sig);
  if (start === -1) return null;
  const ASYNC = 'async ';
  const realStart = (!o.dropAsync && start >= ASYNC.length && content.slice(start - ASYNC.length, start) === ASYNC) ? start - ASYNC.length : start;
  const braceStart = content.indexOf('{', start);
  if (braceStart === -1) return null;
  let depth = 0;
  for (let i = braceStart; i < content.length; i += 1) {
    if (content[i] === '{') depth += 1;
    else if (content[i] === '}') { depth -= 1; if (depth === 0) return content.slice(realStart, i + 1); }
  }
  const closeAt = content.indexOf('\n}\n', start);
  return closeAt === -1 ? null : content.slice(realStart, closeAt + 2);
}
